#!/usr/bin/env python3
"""Печатает список команд проекта.

Вызывается из `make` без аргументов. Отдельный файл нужен по скучной, но
важной причине: команда echo в Windows выводит русский текст в кодировке
консоли, и список получается нечитаемым. Python умеет печатать в UTF-8
на любой системе, поэтому список живёт здесь.
"""

import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

COMMANDS = [
    ("check", "Проверить, что на компьютере есть всё нужное"),
    ("setup", "Создать окружение и поставить зависимости"),
    ("test", "Прогнать все тесты"),
    ("cov", "Тесты с показом покрытия построчно"),
    ("lint", "Проверить стиль кода"),
    ("fmt", "Привести код к единому виду"),
    ("run", "Запустить сервис клиентов на своей машине"),
    ("run-orders", "Запустить сервис заказов"),
    ("migrate", "Применить миграции базы данных"),
    ("up", "Поднять всю систему в контейнерах"),
    ("down", "Остановить систему и удалить данные"),
    ("logs", "Показать журналы сервисов"),
    ("ps", "Показать состояние контейнеров"),
    ("clean", "Удалить окружение и временные файлы"),
]

width = max(len(name) for name, _ in COMMANDS)

print()
print("  Команды проекта")
print()
for name, description in COMMANDS:
    print(f"  make {name.ljust(width)}   {description}")
print()
